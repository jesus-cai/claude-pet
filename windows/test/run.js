// Simula sesiones de Claude Code con el hook real y comprueba qué hace la mascota.
// npm test
'use strict';
const fs = require('fs');
const hook = require('../hook.js');
const { Probe } = require('../lib/probe.js');
const { Brain } = require('../lib/brain.js');
const os = require('os'), path = require('path');
const HOME = path.join(os.tmpdir(), 'compa-test'); fs.rmSync(HOME, {recursive: true, force: true});
const send = (ev, sid, proj, extra = {}) => hook.run(ev, JSON.stringify({session_id: sid, cwd: '/u/' + proj, ...extra}), {home: HOME, noPid: true});
const OK = path.join(os.tmpdir(), 'compa-ok.jsonl'), ERR = path.join(os.tmpdir(), 'compa-err.jsonl');
fs.writeFileSync(OK, '{"type":"assistant","message":{"content":[]}}\n');
fs.writeFileSync(ERR, '{"type":"assistant","isApiErrorMessage":true,"message":{"content":[]}}\n');
const b = new Brain(new Probe(HOME + '/sessions', null), 500);
const said = []; b.speak = (t, tone, tag) => said.push(`[${tone}] ${tag ? tag + ' · ' : ''}${t}`);
b.hush = () => said.push('(calla)');
const alerts = []; b.alert = (e) => alerts.push(e.kind + ':' + e.project);
let userIdle = 0;
const run = (sec) => { for (let i = 0; i < sec * 60; i++) b.step(1/60, {x: 0, y: 0}, {x: 500, y: 900}, userIdle); };
const checks = [];
const expect = (label, act, clip, re) => { const ok = b.activity === act && b.clip === clip && re.test(said.at(-1) || ''); checks.push(ok); console.log(ok ? '✓' : '✗', label, '→', b.activity, b.clip, JSON.stringify(said.at(-1))); };
const show = (label) => { console.log(label.padEnd(34), 'act=' + b.activity.padEnd(11), 'clip=' + b.clip.padEnd(8), 'globo=' + JSON.stringify(said.at(-1) || '')); };
b.wanders = false;
run(0.5);
console.log('— una sesión —');
send('UserPromptSubmit', 'A', 'mi-app'); run(0.5); show('A empieza');
send('PreToolUse', 'A', 'mi-app', {tool_name: 'Read', tool_input: {file_path: '/x/app.ts'}}); run(0.5); show('A lee');
b.beginDrag(); run(0.5); show('la arrastro'); b.endDrag(600); run(0.3); show('la suelto (sigue trabajando?)');
b.wave(); run(2); show('clic y espera 2 s');
send('Stop', 'A', 'mi-app', {transcript_path: OK}); run(0.3); show('A termina');
run(3); show('3 s después (aviso se queda)');
b.acknowledge(); run(0.2); show('clic: visto');
console.log('— varias sesiones —');
send('UserPromptSubmit', 'A', 'mi-app'); send('UserPromptSubmit', 'B', 'api'); send('UserPromptSubmit', 'C', 'web');
run(0.5); send('PreToolUse', 'B', 'api', {tool_name: 'Bash', tool_input: {description: 'run tests'}}); run(0.5); show('tres trabajando');
send('Stop', 'B', 'api', {transcript_path: OK}); run(0.3); show('termina api (no para)');
run(4); show('4 s después (vuelve a trabajo)');
send('Stop', 'C', 'web', {transcript_path: ERR}); run(0.3); show('falla web (no para)');
send('PermissionRequest', 'A', 'mi-app', {tool_name: 'Bash', tool_input: {description: 'deploy'}}); run(0.3); show('mi-app pide permiso');
send('PostToolUse', 'A', 'mi-app', {tool_name: 'Bash'}); run(0.5); show('contestado');
send('Stop', 'A', 'mi-app', {transcript_path: OK}); run(0.3); show('termina la última');
run(3); show('3 s después');
console.log('alertas:', alerts.join(', '));
console.log('— personalidad gruñona —');
b.setPersonality({done: 'waving', drag: 'jumping', work: 'running'}, {done: ['finally.'], start: ['fine…']});
b.acknowledge(); send('UserPromptSubmit', 'A', 'mi-app'); run(0.5); show('empieza');
send('PreToolUse', 'A', 'mi-app', {tool_name: 'Read', tool_input: {file_path: '/x/a.ts'}}); run(0.3); show('lee (work→running fijo)');
send('Stop', 'A', 'mi-app', {transcript_path: OK}); run(0.3); show('termina (asiente, no salta)');
console.log('— comprobaciones —');
b.acknowledge(); b.setPersonality({}, {});
send('UserPromptSubmit', 'X', 'uno'); send('UserPromptSubmit', 'Y', 'dos'); run(0.5);
expect('dos sesiones trabajan', 'working', 'working', /^\[working\] (uno|dos) · /);
send('Stop', 'X', 'uno', {transcript_path: OK}); run(0.3);
expect('acaba una, sigue trabajando', 'working', 'working', /^\[done\] uno · /);
b.beginDrag(); run(0.2); b.endDrag(400); run(0.2);
expect('tras arrastrar vuelve al trabajo', 'working', 'working', /./);
send('Stop', 'Y', 'dos', {transcript_path: OK}); run(0.3);
expect('acaba la última: reacciona y junta', 'celebrating', 'jumping', /^\[done\] dos, uno · /);
if (checks.includes(false)) { console.log('FALLAN', checks.filter((c) => !c).length); process.exit(1); }
console.log('todo bien');
